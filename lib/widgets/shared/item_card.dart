import 'package:flutter/material.dart';
import '../../theme/app_spacing.dart';

/// A task/event/reminder row shown as a card in a list (Archive, Trash,
/// Reminders). The shape comes from `cardTheme`; consecutive cards are
/// spaced by [ItemCardList] or the list's own separator.
class ItemCard extends StatelessWidget {
  const ItemCard({
    super.key,
    this.leading,
    required this.title,
    this.subtitle,
    this.trailing,
    this.onTap,
  });

  final Widget? leading;
  final Widget title;
  final Widget? subtitle;
  final Widget? trailing;
  final VoidCallback? onTap;

  @override
  Widget build(BuildContext context) {
    return Card(
      margin: EdgeInsets.zero,
      clipBehavior: Clip.antiAlias,
      child: ListTile(
        leading: leading,
        title: title,
        subtitle: subtitle,
        trailing: trailing,
        onTap: onTap,
      ),
    );
  }
}

/// Padded, separated list of cards used by the Archive and Trash tabs.
class ItemCardList extends StatelessWidget {
  const ItemCardList({
    super.key,
    required this.itemCount,
    required this.itemBuilder,
  });

  final int itemCount;
  final IndexedWidgetBuilder itemBuilder;

  @override
  Widget build(BuildContext context) {
    return ListView.separated(
      padding: const EdgeInsets.all(AppSpacing.md),
      itemCount: itemCount,
      separatorBuilder: (_, _) => const SizedBox(height: AppSpacing.sm),
      itemBuilder: itemBuilder,
    );
  }
}
